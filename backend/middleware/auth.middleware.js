
const jwt = require("jsonwebtoken");

const authenticateToken = (req, res, next) => {
  const secret = process.env.JWT_SECRET;

  // Server configuration error
  if (!secret || Buffer.byteLength(secret, "utf8") < 32) {
    return res.status(500).json({
      success: false,
      message: "Authentication service is not configured correctly.",
    });
  }

  // Extract the Bearer token
  const authorization = req.headers.authorization;

  if (
    typeof authorization !== "string" ||
    !authorization.startsWith("Bearer ")
  ) {
    return res.status(401).json({
      success: false,
      message: "Authentication token is required.",
    });
  }

  const token = authorization.slice(7).trim();

  if (!token) {
    return res.status(401).json({
      success: false,
      message: "Authentication token is required.",
    });
  }

  try {
    // Verify token signature and required claims
    const decoded = jwt.verify(token, secret, {
      algorithms: ["HS256"],
      issuer: "vaultix-api",
      audience: "vaultix-client",
    });

    // Validate the subject generated by the login controller
    if (
      typeof decoded === "string" ||
      typeof decoded.sub !== "string" ||
      !/^[1-9]\d*$/.test(decoded.sub)
    ) {
      return res.status(401).json({
        success: false,
        message: "Invalid authentication token.",
      });
    }

    // Attach the authenticated user's ID to the request
    req.user = {
      user_id: decoded.sub,
    };

    return next();
  } catch (error) {
    if (
      error.name === "TokenExpiredError" ||
      error.name === "JsonWebTokenError" ||
      error.name === "NotBeforeError"
    ) {
      return res.status(401).json({
        success: false,
        message: "Invalid or expired authentication token.",
      });
    }

    return next(error);
  }
};

module.exports = { authenticateToken };
